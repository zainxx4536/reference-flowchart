#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { pathToFileURL } = require('node:url');
const { staticCheck, checkText } = require('./lib/geometry.cjs');
const { measureTextBounds } = require('./lib/text_bounds.cjs');
const { loadPlaywright, browserPath, applyFont, inspectFonts } = require('./lib/runtime.cjs');
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');

function options(argv) {
  const opts = { scale: 2 };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--overwrite') opts.overwrite = true;
    else if (arg === '--help') {
      console.log('node scripts/export_png.cjs diagram.html [--playwright-module PATH] [--browser-path PATH] [--font-path PATH] [--scale 2] [--overwrite]');
      return null;
    } else if (['--playwright-module', '--browser-path', '--font-path', '--scale'].includes(arg)) {
      if (!argv[i + 1] || argv[i + 1].startsWith('--')) throw Error('Missing value for ' + arg);
      opts[arg.slice(2)] = argv[++i];
    } else if (!opts.html && !arg.startsWith('--')) opts.html = path.resolve(arg);
    else throw Error('Unexpected argument: ' + arg);
  }
  if (!opts.html?.toLowerCase().endsWith('.html')) throw Error('Pass an HTML generated by render_flowchart.py; use --help.');
  opts.scale = Number(opts.scale);
  if (!Number.isFinite(opts.scale) || opts.scale < 1 || opts.scale > 4) throw Error('--scale must be between 1 and 4.');
  return opts;
}

function provenance(spec) {
  const records = ['nodes', 'edges'].flatMap(kind => (spec[kind] || []).map(obj => ({ type: kind.slice(0, -1), id: obj.id, sources: obj.sources || [] })));
  return { scope: 'Declared source locations only; no automatic semantic verification.',
    sourcedNodes: records.filter(r => r.type === 'node' && r.sources.length).length,
    sourcedEdges: records.filter(r => r.type === 'edge' && r.sources.length).length, records };
}

async function exportDiagram(opts) {
  const base = opts.html.slice(0, -5), png = base + '.png', reportFile = base + '.validation.json';
  if (!opts.overwrite && [png, reportFile].some(p => fs.existsSync(p))) throw Error('PNG/report already exists; use another output or --overwrite.');
  const layoutBytes = fs.readFileSync(base + '.layout.json');
  const spec = JSON.parse(layoutBytes.toString('utf8'));
  const html = fs.readFileSync(opts.html, 'utf8'), svgBytes = fs.readFileSync(base + '.svg', 'utf8');
  const embeddedSvg = html.match(/<svg\b[\s\S]*?<\/svg>/)?.[0];
  const layoutHash = sha256(layoutBytes);
  if (!embeddedSvg || embeddedSvg !== svgBytes || !embeddedSvg.includes(`data-layout-sha256="${layoutHash}"`)) throw Error('HTML, SVG and layout do not match. Regenerate all three files with render_flowchart.py.');
  const issues = staticCheck(spec), pw = loadPlaywright(opts['playwright-module']);
  const executablePath = browserPath(opts['browser-path'], pw.api);
  const browser = await pw.api.chromium.launch({ executablePath, headless: true });
  const tempPng = png + `.tmp-${process.pid}`, tempReport = reportFile + `.tmp-${process.pid}`;
  try {
    const page = await browser.newPage({ viewport: { width: Math.min(2400, Math.ceil(spec.canvas.width + 40)), height: 1000 }, deviceScaleFactor: opts.scale });
    await page.route(/^https?:\/\//, route => route.abort());
    page.on('pageerror', error => issues.push({ type: 'browser-error', message: error.message }));
    await page.goto(pathToFileURL(opts.html).href, { waitUntil: 'load' });
    await applyFont(page, opts['font-path']);
    await page.evaluate(() => document.fonts.ready);
    const fonts = await inspectFonts(page);
    if (fonts.missingGlyphs.length) issues.push({ type: 'missing-cjk-glyphs', characters: fonts.missingGlyphs });
    const bounds = await page.evaluate(measureTextBounds);
    issues.push(...checkText(spec, bounds));
    const svg = page.locator('#flowchart');
    await svg.evaluate(el => {
      const view = el.viewBox.baseVal;
      for (const name of ['width', 'min-width', 'max-width']) el.style.setProperty(name, view.width + 'px', 'important');
      el.style.setProperty('height', view.height + 'px', 'important');
      for (let p = el.parentElement; p; p = p.parentElement) p.style.setProperty('overflow', 'visible', 'important');
    });
    await svg.scrollIntoViewIfNeeded();
    const box = await svg.boundingBox();
    await svg.evaluate((el, delta) => { el.style.position = 'relative'; el.style.top = delta + 'px'; }, Math.round(box.y) - box.y);
    await svg.screenshot({ path: tempPng, type: 'png' });
    const data = fs.readFileSync(tempPng), pngSize = { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
    if (pngSize.width !== Math.round(spec.canvas.width * opts.scale) || pngSize.height !== Math.round(spec.canvas.height * opts.scale)) issues.push({ type: 'unexpected-png-size', pngSize });
    await page.reload({ waitUntil: 'load' });
    await applyFont(page, opts['font-path']);
    await page.setViewportSize({ width: 900, height: 800 });
    await page.evaluate(() => document.fonts.ready);
    const fit = await page.evaluate(() => {
      const scroll = document.documentElement.scrollWidth, client = document.documentElement.clientWidth;
      for (const details of document.querySelectorAll('details')) details.open = true;
      return { scroll, client, expandedScroll: document.documentElement.scrollWidth };
    });
    if (fit.scroll > fit.client + 1 || fit.expandedScroll > fit.client + 1) issues.push({ type: 'page-overflow-in-fit-mode', fit });
    await page.locator('#scale').click();
    const actual = await svg.boundingBox();
    if (Math.abs(actual.width - spec.canvas.width) > 1) issues.push({ type: 'original-size-toggle-failed' });
    const report = {
      status: issues.length ? 'needs-fix' : 'layout-pass',
      scope: 'Geometry, fonts and browser rendering. Review semantics independently and inspect the PNG.',
      hashes: { layout: layoutHash, svg: sha256(svgBytes), png: sha256(data) },
      runtime: { platform: process.platform, node: process.versions.node, playwright: pw.version, browser: browser.version() },
      fonts, pngSize, fit, nodes: spec.nodes.length, zones: (spec.zones || []).length, edges: (spec.edges || []).length,
      declaredPaths: spec.paths || [], provenance: provenance(spec), geometry: { bounds }, issues,
    };
    fs.writeFileSync(tempReport, JSON.stringify(report, null, 2) + '\n', 'utf8');
    fs.renameSync(tempPng, png); fs.renameSync(tempReport, reportFile);
    return { report, png, reportFile };
  } finally {
    await browser.close();
    for (const temp of [tempPng, tempReport]) if (fs.existsSync(temp)) fs.unlinkSync(temp);
  }
}

async function main() {
  const opts = options(process.argv.slice(2));
  if (!opts) return;
  const { report, png, reportFile } = await exportDiagram(opts);
  console.log(JSON.stringify({ status: report.status, png, report: reportFile, pngSize: report.pngSize, issues: report.issues }));
  if (report.issues.length) process.exitCode = 1;
}
if (require.main === module) main().catch(error => { console.error('PNG export failed: ' + error.message); process.exitCode = 1; });
module.exports = { options, exportDiagram, provenance };
