#!/usr/bin/env node
// Browser export and layout-only QA for render_flowchart.py output.
// No network installation; use an existing Playwright module and browser.
const fs = require('fs');
const path = require('path');
const os = require('os');
const {pathToFileURL} = require('url');

function options(argv) {
  const out={scale:2};
  for(let i=0;i<argv.length;i++){
    const a=argv[i];
    if(a==='--overwrite')out.overwrite=true;
    else if(a==='--help'){console.log('node export_png.cjs diagram.html [--playwright-module PATH] [--browser-path PATH] [--scale 2] [--overwrite]');process.exit(0);}
    else if(['--playwright-module','--browser-path','--scale'].includes(a)){
      if(!argv[i+1]||argv[i+1].startsWith('--'))throw Error('Missing value for '+a);
      out[a.slice(2)]=argv[++i];
    }else if(!out.html&&!a.startsWith('--'))out.html=path.resolve(a);
    else throw Error('Unexpected argument: '+a);
  }
  if(!out.html||!out.html.toLowerCase().endsWith('.html'))throw Error('Pass an HTML file generated by render_flowchart.py; use --help for options.');
  out.scale=Number(out['scale']);
  if(!Number.isFinite(out.scale)||out.scale<1||out.scale>4)throw Error('--scale must be between 1 and 4.');
  return out;
}

function loadPlaywright(arg) {
  const explicit=arg||process.env.FLOWCHART_PLAYWRIGHT_MODULE;
  if(explicit)return require(path.resolve(explicit));
  for(const candidate of ['playwright',path.join(os.homedir(),'.cache','codex-runtimes','codex-primary-runtime','dependencies','node','node_modules','playwright')]){
    try{return require(candidate);}catch(e){if(e.code!=='MODULE_NOT_FOUND')throw e;}
  }
  throw Error('Existing Playwright module not found. Discover workspace dependencies and pass --playwright-module; no packages were installed.');
}

function browserPath(arg,pw) {
  const explicit=arg||process.env.FLOWCHART_BROWSER_PATH;
  if(explicit){
    if(!fs.existsSync(explicit))throw Error('Browser executable does not exist: '+explicit);
    return explicit;
  }
  const candidates=[
    pw.chromium.executablePath(),
    ...['ProgramFiles','ProgramFiles(x86)','LOCALAPPDATA'].flatMap(k=>process.env[k]?[
      path.join(process.env[k],'Google','Chrome','Application','chrome.exe'),
      path.join(process.env[k],'Microsoft','Edge','Application','msedge.exe')
    ]:[]),
    '/usr/bin/chromium','/usr/bin/chromium-browser','/usr/bin/google-chrome',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
  ];
  const found=candidates.find(p=>p&&fs.existsSync(p));
  if(!found)throw Error('Existing Chromium browser not found. Pass --browser-path; no browser was installed.');
  return found;
}

function interiorHit(p,q,n){
  const l=n.x+.8,r=n.x+n.width-.8,t=n.y+.8,b=n.y+n.height-.8;
  return p[0]===q[0]
    ?p[0]>l&&p[0]<r&&Math.max(p[1],q[1])>t&&Math.min(p[1],q[1])<b
    :p[1]>t&&p[1]<b&&Math.max(p[0],q[0])>l&&Math.min(p[0],q[0])<r;
}
function boundary(p,obj){
  if(obj.width===undefined)return Math.hypot(p[0]-obj.x,p[1]-obj.y)<=1;
  const x=p[0],y=p[1],l=obj.x,r=l+obj.width,t=obj.y,b=t+obj.height;
  return (Math.min(Math.abs(x-l),Math.abs(x-r))<=1&&y>=t-1&&y<=b+1)||
    (Math.min(Math.abs(y-t),Math.abs(y-b))<=1&&x>=l-1&&x<=r+1);
}
function overlaps(a,b){return Math.min(a.x+a.width,b.x+b.width)>Math.max(a.x,b.x)+1&&Math.min(a.y+a.height,b.y+b.height)>Math.max(a.y,b.y)+1;}
function staticCheck(spec){
  const issues=[],objects=new Map([...spec.nodes,...(spec.zones||[]),...(spec.junctions||[])].map(o=>[o.id,o]));
  const edges=spec.edges||[];
  for(const e of edges){
    for(const [id,p] of [[e.from,e.points[0]],[e.to,e.points[e.points.length-1]]]){
      if(!boundary(p,objects.get(id)))issues.push({type:'port-not-on-boundary',edge:e.id,object:id,point:p});
    }
    for(let i=1;i<e.points.length;i++)for(const n of spec.nodes){
      if(n.id!==e.from&&n.id!==e.to&&interiorHit(e.points[i-1],e.points[i],n))
        issues.push({type:'connector-through-unrelated-node',edge:e.id,node:n.id});
    }
  }
  for(let i=0;i<spec.nodes.length;i++)for(let j=i+1;j<spec.nodes.length;j++)
    if(overlaps(spec.nodes[i],spec.nodes[j]))issues.push({type:'overlapping-nodes',nodes:[spec.nodes[i].id,spec.nodes[j].id]});
  // Strict crossings away from segment endpoints need an explicit junction.
  for(let a=0;a<edges.length;a++)for(let b=a+1;b<edges.length;b++)
    for(let i=1;i<edges[a].points.length;i++)for(let j=1;j<edges[b].points.length;j++){
      let p=edges[a].points[i-1],q=edges[a].points[i],r=edges[b].points[j-1],s=edges[b].points[j];
      if((p[0]===q[0])===(r[0]===s[0]))continue;
      if(p[0]===q[0]){[p,r]=[r,p];[q,s]=[s,q];}
      const cross=[r[0],p[1]];
      if(cross[0]>Math.min(p[0],q[0])&&cross[0]<Math.max(p[0],q[0])&&cross[1]>Math.min(r[1],s[1])&&cross[1]<Math.max(r[1],s[1])&&
         !(spec.junctions||[]).some(n=>Math.hypot(n.x-cross[0],n.y-cross[1])<1))
        issues.push({type:'unmarked-crossing',edges:[edges[a].id,edges[b].id],point:cross});
    }
  return issues;
}

async function main(){
  const opts=options(process.argv.slice(2));
  const base=opts.html.slice(0,-5);
  const png=base+'.png',reportFile=base+'.validation.json';
  if(!opts.overwrite&&(fs.existsSync(png)||fs.existsSync(reportFile)))throw Error('PNG/report already exists. Use another output or explicitly pass --overwrite.');
  const spec=JSON.parse(fs.readFileSync(base+'.layout.json','utf8'));
  const issues=staticCheck(spec);
  const pw=loadPlaywright(opts['playwright-module']);
  const browser=await pw.chromium.launch({executablePath:browserPath(opts['browser-path'],pw),headless:true});
  try{
    const page=await browser.newPage({viewport:{width:Math.min(2400,Math.ceil(spec.canvas.width+40)),height:1000},deviceScaleFactor:opts.scale});
    page.on('pageerror',e=>issues.push({type:'browser-error',message:e.message}));
    await page.goto(pathToFileURL(opts.html).href,{waitUntil:'load'});
    await page.evaluate(()=>document.fonts.ready);
    const geometry=await page.evaluate(()=>{
      const svg=document.getElementById('flowchart'),v=svg.viewBox.baseVal;
      const failures=[],bounds=[];
      const bbox=el=>{const b=el.getBBox();return{x:b.x,y:b.y,width:b.width,height:b.height};};
      const nodes=[...svg.querySelectorAll('.node')];
      for(const n of nodes){
        const [x,y,w,h]=n.dataset.box.split(',').map(Number),padY=Number(n.dataset.paddingY);
        for(const t of n.querySelectorAll('text')){
          const b=bbox(t);bounds.push({node:n.id,text:t.textContent,bounds:b});
          if(b.x<x+7||b.x+b.width>x+w-7||b.y<y+padY||b.y+b.height>y+h-padY)
            failures.push({type:'text-outside-content-box',node:n.id,text:t.textContent,bounds:b});
        }
      }
      for(const t of svg.querySelectorAll('text')){
        const b=bbox(t);
        if(b.x<0||b.y<0||b.x+b.width>v.width||b.y+b.height>v.height)failures.push({type:'text-outside-canvas',text:t.textContent,bounds:b});
        // Free labels and zone titles should not overlap a processing box.
        if(!t.closest('.node'))for(const n of nodes){
          const [x,y,w,h]=n.dataset.box.split(',').map(Number);
          if(Math.min(b.x+b.width,x+w)>Math.max(b.x,x)+1&&Math.min(b.y+b.height,y+h)>Math.max(b.y,y)+1)
            failures.push({type:'label-overlaps-node',node:n.id,text:t.textContent});
        }
      }
      return{failures,bounds,fontFamily:getComputedStyle(svg).fontFamily};
    });
    issues.push(...geometry.failures);
    const svg=page.locator('#flowchart');
    await svg.evaluate(el=>{
      const v=el.viewBox.baseVal;
      for(const name of ['width','min-width','max-width'])el.style.setProperty(name,v.width+'px','important');
      el.style.setProperty('height',v.height+'px','important');
      for(let p=el.parentElement;p;p=p.parentElement)p.style.setProperty('overflow','visible','important');
    });
    await svg.scrollIntoViewIfNeeded();
    const b=await svg.boundingBox();
    await svg.evaluate((el,delta)=>{el.style.position='relative';el.style.top=delta+'px'},Math.round(b.y)-b.y);
    await svg.screenshot({path:png});
    const data=fs.readFileSync(png),pngSize={width:data.readUInt32BE(16),height:data.readUInt32BE(20)};
    if(pngSize.width!==Math.round(spec.canvas.width*opts.scale)||pngSize.height!==Math.round(spec.canvas.height*opts.scale))
      issues.push({type:'unexpected-png-size',pngSize});
    await page.reload({waitUntil:'load'});
    await page.setViewportSize({width:900,height:800});
    await page.evaluate(()=>document.fonts.ready);
    const fit=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
    if(fit.scroll>fit.client+1)issues.push({type:'page-overflow-in-fit-mode',fit});
    await page.locator('#scale').click();
    const actual=await page.locator('#flowchart').boundingBox();
    if(Math.abs(actual.width-spec.canvas.width)>1)issues.push({type:'original-size-toggle-failed'});
    const report={status:issues.length?'needs-fix':'layout-pass',scope:'Geometry and browser rendering only; inspect the PNG and independently review semantics.',pngSize,fit,
      nodes:spec.nodes.length,zones:(spec.zones||[]).length,edges:(spec.edges||[]).length,declaredPaths:spec.paths||[],geometry,issues};
    fs.writeFileSync(reportFile,JSON.stringify(report,null,2),'utf8');
    console.log(JSON.stringify({status:report.status,png,report:reportFile,pngSize,issues}));
    if(issues.length)process.exitCode=1;
  }finally{await browser.close();}
}
main().catch(e=>{console.error('PNG export failed: '+e.message);process.exitCode=1;});
